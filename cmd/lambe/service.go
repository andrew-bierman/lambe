const (
	launchdLabel = "com.lambe.daemon"
	systemdUnit  = "lambe.service"
)

// sysEnv is the slice of the host that service management touches. Tests
// swap Run for a fake so no real launchctl or systemctl ever executes.
type sysEnv struct {
	GOOS string
	Home string
	UID  int
	// Run executes a command and returns its combined output.
	Run func(ctx context.Context, name string, args ...string) (string, error)
}

func hostEnv() sysEnv {
	home, _ := os.UserHomeDir()
	return sysEnv{GOOS: runtime.GOOS, Home: home, UID: os.Getuid(), Run: runCombined}
}

func runCombined(ctx context.Context, name string, args ...string) (string, error) {
	var buf bytes.Buffer
	cmd := exec.CommandContext(ctx, name, args...) // #nosec G204 -- fixed service-manager argv
	cmd.Stdout, cmd.Stderr = &buf, &buf
	err := cmd.Run()
	return buf.String(), err
}

// managerFor picks the init system: an explicit override wins, otherwise
// the host OS decides.
func (e sysEnv) managerFor(override string) (string, error) {
	switch override {
	case "launchd", "systemd":
		return override, nil
	case "":
	default:
		return "", fmt.Errorf("unknown service manager %q; choose launchd or systemd", override)
	}
	switch e.GOOS {
	case "darwin":
		return "launchd", nil
	case "linux":
		return "systemd", nil
	}
	return "", fmt.Errorf("no supported service manager on %s", e.GOOS)
}

// unitPath is where the unit lives under root (the home directory when
// root is empty).
func (e sysEnv) unitPath(manager, root string) string {
	if root == "" {
		root = e.Home
	}
	if manager == "launchd" {
		return filepath.Join(root, "Library", "LaunchAgents", launchdLabel+".plist")
	}
	return filepath.Join(root, ".config", "systemd", "user", systemdUnit)
}

func (e sysEnv) logPath() string {
	return filepath.Join(e.Home, "Library", "Logs", "lambe", "daemon.log")
}

// unitParams are the values interpolated into a generated unit.
type unitParams struct {
	Binary, Config, Path, Log string
}

var plistTemplate = template.Must(template.New("plist").Funcs(template.FuncMap{"xml": xmlEscape}).Parse(`<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by lambe service install. KeepAlive restarts the daemon on any
     exit; the state lock makes a doubled start harmless (exit 3). -->
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>` + launchdLabel + `</string>
    <key>ProgramArguments</key>
    <array>
        <string>{{xml .Binary}}</string>
        <string>run</string>
        <string>-config</string>
        <string>{{xml .Config}}</string>
    </array>
    <!-- launchd starts jobs with a minimal PATH; without this the daemon
         cannot find bd or the agent harness. -->
    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key>
        <string>{{xml .Path}}</string>
    </dict>
    <key>KeepAlive</key>
    <true/>
    <key>RunAtLoad</key>
    <true/>
    <key>ProcessType</key>
    <string>Background</string>
    <!-- Room for the daemon's SIGTERM -> grace -> SIGKILL ladder; launchd's
         default of 20s would cut it short. -->
    <key>ExitTimeOut</key>
    <integer>45</integer>
    <key>StandardOutPath</key>
    <string>{{xml .Log}}</string>
    <key>StandardErrorPath</key>
    <string>{{xml .Log}}</string>
</dict>
</plist>
`))

var systemdTemplate = template.Must(template.New("unit").Parse(`# Generated by lambe service install.
# The state lock makes a doubled start harmless: the second instance exits 3.
[Unit]
Description=lambe supervisor daemon
After=network-online.target

[Service]
Type=simple
ExecStart={{.Binary}} run --config {{.Config}}
Environment={{.Path}}
Restart=on-failure
RestartSec=5
# Room for the daemon's SIGTERM -> grace -> SIGKILL ladder.
TimeoutStopSec=45
# Exit code 3 means another instance holds the lock: nothing to restart.
SuccessExitStatus=3

[Install]
WantedBy=default.target
`))

func xmlEscape(s string) string { return html.EscapeString(s) }

// systemdQuote quotes one ExecStart/Environment word. systemd expands
// %specifiers and $VARS inside quotes too, so both are doubled.
func systemdQuote(s string) (string, error) {
	if strings.ContainsAny(s, "\"\\\n") {
		return "", fmt.Errorf("path %q contains a character systemd units cannot carry", s)
	}
	s = strings.NewReplacer("%", "%%", "$", "$$").Replace(s)
	return `"` + s + `"`, nil
}

// renderUnit generates the unit text for manager.
func renderUnit(manager string, p unitParams) (string, error) {
	var buf bytes.Buffer
	if manager == "launchd" {
		if err := plistTemplate.Execute(&buf, p); err != nil {
			return "", err
		}
		return buf.String(), nil
	}
	var err error
	q := p
	if q.Binary, err = systemdQuote(p.Binary); err != nil {
		return "", err
	}
	if q.Config, err = systemdQuote(p.Config); err != nil {
		return "", err
	}
	if q.Path, err = systemdQuote("PATH=" + p.Path); err != nil {
		return "", err
	}
	if err := systemdTemplate.Execute(&buf, q); err != nil {
		return "", err
	}
	return buf.String(), nil
}

// serviceState is what status (and doctor) learn about the installed unit.
type serviceState struct {
	Manager   string
	Path      string
	Installed bool
	// Queried is false when the manager was not asked (sandboxed --root).
	Queried bool
	Running bool
	Detail  string
	Unit    string // unit file contents when installed
}

// queryService inspects the unit file and, when query is true, asks the
// init system whether it is loaded and running. It never changes anything.
func queryService(ctx context.Context, e sysEnv, manager, root string, query bool) serviceState {
	st := serviceState{Manager: manager, Path: e.unitPath(manager, root)}
	data, err := os.ReadFile(st.Path) // #nosec G304 -- derived from the home directory
	if err != nil {
		st.Detail = "no unit file at " + st.Path
		return st
	}
	st.Installed, st.Unit = true, string(data)
	if !query {
		st.Detail = "unit file present (service manager not queried)"
		return st
	}
	st.Queried = true
	ctx, cancel := context.WithTimeout(ctx, 5*time.Second)
	defer cancel()
	if manager == "launchd" {
		out, err := e.Run(ctx, "launchctl", "print", fmt.Sprintf("gui/%d/%s", e.UID, launchdLabel))
		switch {
		case err != nil:
			st.Detail = "unit file present but not loaded in launchd"
		case regexp.MustCompile(`(?m)^\s*pid = \d+`).MatchString(out):
			st.Running, st.Detail = true, "loaded and running in launchd"
		default:
			st.Detail = "loaded in launchd but not running"
		}
		return st
	}
	out, _ := e.Run(ctx, "systemctl", "--user", "is-active", systemdUnit)
	state := strings.TrimSpace(out)
	st.Running = state == "active"
	st.Detail = "systemd user unit is " + state
	return st
}

// runService dispatches `lambe service install|status|uninstall`.
func runService(args []string, e sysEnv, out io.Writer) error {
	if len(args) == 0 {
		return errors.New("usage: lambe service install|status|uninstall [flags]")
	}
	fs := flag.NewFlagSet("lambe service "+args[0], flag.ContinueOnError)
	configFile := fs.String("config", "", "config file the service runs with (install; default: the default config path)")
	root := fs.String("root", "", "write the unit under this directory instead of $HOME and never call launchctl/systemctl")
	manager := fs.String("manager", "", "launchd or systemd (default: by OS)")
	dryRun := fs.Bool("dry-run", false, "print the unit and its destination without writing anything (install)")
	noStart := fs.Bool("no-start", false, "write the unit but do not load/start it (install)")
	force := fs.Bool("force", false, "replace a different existing unit (install)")
	if err := fs.Parse(args[1:]); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return nil
		}
		return err
	}
	mgr, err := e.managerFor(*manager)
	if err != nil {
		return err
	}
	// A --root install is a sandbox: touching the real service manager
	// from there would load a unit that lives elsewhere.
	live := *root == ""
	ctx := context.Background()

	switch args[0] {
	case "install":
		return serviceInstall(ctx, e, out, mgr, *root, *configFile, *dryRun, *noStart || !live, *force)
	case "status":
		st := queryService(ctx, e, mgr, *root, live)
		say(out, "manager: %s\nunit:    %s\nstatus:  %s\n", st.Manager, st.Path, st.Detail)
		if !st.Installed || (st.Queried && !st.Running) {
			return errors.New("lambe service is not running; run `lambe service install`")
		}
		return nil
	case "uninstall":
		return serviceUninstall(ctx, e, out, mgr, *root, live)
	}
	return fmt.Errorf("unknown service command %q; choose install, status, or uninstall", args[0])
}

func serviceInstall(ctx context.Context, e sysEnv, out io.Writer, mgr, root, configFile string, dryRun, noStart, force bool) error {
	bin, err := os.Executable()
	if err != nil {
		return fmt.Errorf("locate lambe binary: %w", err)
	}
	if resolved, err := filepath.EvalSymlinks(bin); err == nil {
		bin = resolved
	}
	cfgPath := configFile
	if cfgPath == "" {
		cfgPath = config.DefaultPath()
	}
	if cfgPath, err = filepath.Abs(cfgPath); err != nil {
		return err
	}
	if _, err := os.Stat(cfgPath); err != nil && !dryRun { // #nosec G703 -- operator-supplied config path
		return fmt.Errorf("config %s: %w; run `lambe init` first (or pass -config FILE)", cfgPath, err)
	}
	unit, err := renderUnit(mgr, unitParams{Binary: bin, Config: cfgPath, Path: servicePATH(e.Home), Log: e.logPath()})
	if err != nil {
		return err
	}
	path := e.unitPath(mgr, root)
	if dryRun {
		say(out, "# would write %s\n%s", path, unit)
		return nil
	}
	existing, readErr := os.ReadFile(path) // #nosec G304 -- derived from the home directory
	if readErr == nil && string(existing) != unit && !force {
		return fmt.Errorf("%s exists with different content; re-run with --force to replace it", path)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o750); err != nil {
		return err
	}
	if mgr == "launchd" {
		// launchd does not create the log directory; a missing one fails the job silently.
		if err := os.MkdirAll(filepath.Dir(e.logPath()), 0o750); err != nil {
			return err
		}
	}
	if err := os.WriteFile(path, []byte(unit), 0o600); err != nil {
		return err
	}
	say(out, "wrote %s\n", path)
	if noStart {
		say(out, "not started; load it with `lambe service install` (without --root/--no-start)\n")
		return nil
	}
	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()
	for _, c := range startCommands(e, mgr, path, readErr == nil) {
		if o, err := e.Run(ctx, c.argv[0], c.argv[1:]...); err != nil && !c.optional {
			return fmt.Errorf("%s: %w: %s", strings.Join(c.argv, " "), err, strings.TrimSpace(o))
		}
	}
	say(out, "started; check with `lambe service status` and `lambe doctor`\n")
	return nil
}

type serviceCmd struct {
	argv     []string
	optional bool // failure is tolerated
}

// startCommands is the load sequence. A replaced unit is booted out first
// so launchd picks up the new definition; that step is allowed to fail.
func startCommands(e sysEnv, mgr, path string, replacing bool) []serviceCmd {
	if mgr == "launchd" {
		domain := fmt.Sprintf("gui/%d", e.UID)
		var cmds []serviceCmd
		if replacing {
			cmds = append(cmds, serviceCmd{[]string{"launchctl", "bootout", domain + "/" + launchdLabel}, true})
		}
		return append(cmds, serviceCmd{[]string{"launchctl", "bootstrap", domain, path}, false})
	}
	return []serviceCmd{
		{[]string{"systemctl", "--user", "daemon-reload"}, false},
		{[]string{"systemctl", "--user", "enable", "--now", systemdUnit}, false},
	}
}

func serviceUninstall(ctx context.Context, e sysEnv, out io.Writer, mgr, root string, live bool) error {
	path := e.unitPath(mgr, root)
	if live {
		ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
		defer cancel()
		// Best effort: the unit may never have been loaded.
		if mgr == "launchd" {
			_, _ = e.Run(ctx, "launchctl", "bootout", fmt.Sprintf("gui/%d/%s", e.UID, launchdLabel))
		} else {
			_, _ = e.Run(ctx, "systemctl", "--user", "disable", "--now", systemdUnit)
		}
	}
	if err := os.Remove(path); err != nil && !errors.Is(err, os.ErrNotExist) {
		return err
	}
	if live && mgr == "systemd" {
		_, _ = e.Run(ctx, "systemctl", "--user", "daemon-reload")
	}
	say(out, "removed %s\n", path)
	return nil
}

// servicePATH is the PATH baked into the unit. It is deliberately not a
// copy of the installer's PATH (which carries session-specific temp
// directories): just the system and user bin directories, plus wherever the
// tools the daemon shells out to are installed right now.
func servicePATH(home string) string {
	dirs := []string{filepath.Join(home, ".local", "bin"), "/opt/homebrew/bin", "/usr/local/bin", "/usr/bin", "/bin", "/usr/sbin", "/sbin"}
	if shims := filepath.Join(home, ".local", "share", "mise", "shims"); dirExists(shims) {
		dirs = append(dirs, shims)
	}
	for _, tool := range []string{"bd", "pi", "codex", "node", "git", "gh"} {
		if p, err := exec.LookPath(tool); err == nil {
			dirs = append(dirs, filepath.Dir(p))
		}
	}
	seen := map[string]bool{}
	var uniq []string
	for _, d := range dirs {
		if !seen[d] {
			seen[d] = true
			uniq = append(uniq, d)
		}
	}
	return strings.Join(uniq, string(os.PathListSeparator))
}

func dirExists(p string) bool {
	info, err := os.Stat(p)
	return err == nil && info.IsDir()
}
