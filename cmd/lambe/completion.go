package main

import (
	"errors"
	"flag"
	"fmt"
	"io"
	"regexp"
	"strings"
)

// completionSpec is what a shell completion needs to know about one command
// page: its flags (with a description and whether the value is a file) and,
// for a command group, its subcommands.
type completionSpec struct {
	summary string
	flags   []completionFlag
	subs    []string
}

type completionFlag struct {
	name string // "--config"
	desc string
	// values lists the fixed choices of the flag's value ("pi|codex|acp"),
	// file marks a path-valued flag, takesValue marks any other value.
	values     []string
	file       bool
	takesValue bool
}

// flagLine matches a flag entry of a help page: "  --config FILE   text".
var flagLine = regexp.MustCompile(`^  (--[\w-]+)(?: (\S+))?\s{2,}(\S.*)$`)

// completionSpecs derives every completable page from helpTopics, so the
// completions can never drift from the help text. The key is the page name:
// "init", "service install".
func completionSpecs() (order []string, specs map[string]completionSpec) {
	specs = map[string]completionSpec{}
	for _, t := range helpTopics {
		spec := completionSpec{summary: t.summary}
		inFlags := false
		for _, line := range strings.Split(t.body, "\n") {
			switch {
			case strings.HasPrefix(line, "flags:"):
				inFlags = true
			case line != "" && !strings.HasPrefix(line, " "):
				inFlags = false
			case inFlags:
				if m := flagLine.FindStringSubmatch(line); m != nil {
					spec.flags = append(spec.flags, parseCompletionFlag(m[1], m[2], m[3]))
				}
			}
		}
		specs[t.name] = spec
		order = append(order, t.name)
	}
	for _, name := range order {
		if parent, sub, ok := strings.Cut(name, " "); ok {
			p := specs[parent]
			p.subs = append(p.subs, sub)
			specs[parent] = p
		}
	}
	return order, specs
}

func parseCompletionFlag(name, arg, desc string) completionFlag {
	f := completionFlag{name: name, desc: desc, takesValue: arg != ""}
	switch {
	case strings.Contains(arg, "|"):
		f.values = strings.Split(arg, "|")
	case arg == "FILE" || arg == "PATH" || arg == "DIR":
		f.file = true
	}
	return f
}

// topCommands lists the top-level command names in help order.
func topCommands(order []string, specs map[string]completionSpec) []string {
	var names []string
	for _, n := range order {
		if !strings.Contains(n, " ") && specs[n].summary != "" {
			names = append(names, n)
		}
	}
	return names
}

// completionScript returns the completion script for shell.
func completionScript(shell string) (string, error) {
	order, specs := completionSpecs()
	switch shell {
	case "bash":
		return bashCompletion(order, specs), nil
	case "zsh":
		return zshCompletion(order, specs), nil
	case "fish":
		return fishCompletion(order, specs), nil
	}
	return "", usageError{fmt.Errorf("unknown shell %q; choose bash, zsh, or fish", shell)}
}

func flagNames(flags []completionFlag) string {
	names := make([]string, len(flags))
	for i, f := range flags {
		names[i] = f.name
	}
	return strings.Join(names, " ")
}

func bashCompletion(order []string, specs map[string]completionSpec) string {
	var b strings.Builder
	b.WriteString("# bash completion for lambe; generated by `lambe completion bash`.\n_lambe() {\n")
	b.WriteString("  local cur prev cmd page\n  cur=\"${COMP_WORDS[COMP_CWORD]}\"\n  prev=\"${COMP_WORDS[COMP_CWORD-1]}\"\n  cmd=\"${COMP_WORDS[1]}\"\n")
	fmt.Fprintf(&b, "  if (( COMP_CWORD == 1 )); then\n    COMPREPLY=( $(compgen -W %q -- \"$cur\") )\n    return\n  fi\n", strings.Join(append(topCommands(order, specs), "--help", "--version"), " "))
	// Value completion for the previous flag.
	b.WriteString("  case \"$prev\" in\n")
	seen := map[string]bool{}
	for _, name := range order {
		for _, f := range specs[name].flags {
			if seen[f.name] || !f.takesValue {
				continue
			}
			seen[f.name] = true
			switch {
			case f.file:
				fmt.Fprintf(&b, "    %s) COMPREPLY=( $(compgen -f -- \"$cur\") ); return ;;\n", f.name)
			case len(f.values) > 0:
				fmt.Fprintf(&b, "    %s) COMPREPLY=( $(compgen -W %q -- \"$cur\") ); return ;;\n", f.name, strings.Join(f.values, " "))
			default:
				fmt.Fprintf(&b, "    %s) return ;;\n", f.name)
			}
		}
	}
	b.WriteString("  esac\n  page=\"$cmd\"\n")
	b.WriteString("  if [[ -n \"${COMP_WORDS[2]}\" && \"${COMP_WORDS[2]}\" != -* ]]; then page=\"$cmd ${COMP_WORDS[2]}\"; fi\n")
	b.WriteString("  case \"$page\" in\n")
	for _, name := range order {
		spec := specs[name]
		words := flagNames(spec.flags)
		if !strings.Contains(name, " ") && len(spec.subs) > 0 {
			// A group's bare page completes subcommands first.
			fmt.Fprintf(&b, "    %q)\n      if (( COMP_CWORD == 2 )); then COMPREPLY=( $(compgen -W %q -- \"$cur\") ); fi ;;\n", name, strings.Join(spec.subs, " "))
			continue
		}
		fmt.Fprintf(&b, "    %q) COMPREPLY=( $(compgen -W %q -- \"$cur\") ) ;;\n", name, words)
	}
	b.WriteString("    help) COMPREPLY=( $(compgen -W \"$(lambe help 2>/dev/null | awk '/^commands:/{f=1;next} /^$/{f=0} f{print $1}')\" -- \"$cur\") ) ;;\n")
	b.WriteString("  esac\n}\ncomplete -F _lambe lambe\n")
	return b.String()
}

func zshCompletion(order []string, specs map[string]completionSpec) string {
	var b strings.Builder
	b.WriteString("#compdef lambe\n# zsh completion for lambe; generated by `lambe completion zsh`.\n\n_lambe() {\n  local -a commands subs flags\n  local page\n")
	b.WriteString("  commands=(\n")
	for _, n := range topCommands(order, specs) {
		fmt.Fprintf(&b, "    '%s:%s'\n", n, zshQuote(specs[n].summary))
	}
	b.WriteString("  )\n  if (( CURRENT == 2 )); then\n    _describe -t commands 'lambe command' commands\n    return\n  fi\n")
	b.WriteString("  page=\"${words[2]}\"\n  if [[ -n \"${words[3]}\" && \"${words[3]}\" != -* && $CURRENT -gt 3 ]]; then page=\"${words[2]} ${words[3]}\"; fi\n")
	b.WriteString("  case \"$page\" in\n")
	for _, name := range order {
		spec := specs[name]
		fmt.Fprintf(&b, "    %q)\n", name)
		if !strings.Contains(name, " ") && len(spec.subs) > 0 {
			fmt.Fprintf(&b, "      if (( CURRENT == 3 )); then subs=(%s); _describe -t subcommands 'subcommand' subs; return; fi\n", zshWords(spec.subs))
		}
		b.WriteString("      _arguments")
		for _, f := range spec.flags {
			b.WriteString(" " + zshFlag(f))
		}
		b.WriteString(" '*:argument:_files' ;;\n")
	}
	b.WriteString("  esac\n}\n\n_lambe \"$@\"\n")
	return b.String()
}

func zshQuote(s string) string { return strings.NewReplacer("'", "'\\''", ":", "\\:").Replace(s) }

func zshWords(words []string) string {
	q := make([]string, len(words))
	for i, w := range words {
		q[i] = "'" + w + "'"
	}
	return strings.Join(q, " ")
}

func zshFlag(f completionFlag) string {
	spec := "'" + f.name
	if f.takesValue {
		spec += "="
	}
	spec += "[" + strings.NewReplacer("'", "", "[", "(", "]", ")").Replace(f.desc) + "]"
	switch {
	case f.file:
		spec += ":file:_files"
	case len(f.values) > 0:
		spec += ":value:(" + strings.Join(f.values, " ") + ")"
	case f.takesValue:
		spec += ": :"
	}
	return spec + "'"
}

func fishCompletion(order []string, specs map[string]completionSpec) string {
	var b strings.Builder
	b.WriteString("# fish completion for lambe; generated by `lambe completion fish`.\ncomplete -c lambe -f\n")
	for _, n := range topCommands(order, specs) {
		fmt.Fprintf(&b, "complete -c lambe -n __fish_use_subcommand -a %s -d %s\n", n, fishQuote(specs[n].summary))
	}
	for _, name := range order {
		spec := specs[name]
		parent, sub, isSub := strings.Cut(name, " ")
		cond := "__fish_seen_subcommand_from " + name
		if isSub {
			cond = fmt.Sprintf("__fish_seen_subcommand_from %s; and __fish_seen_subcommand_from %s", parent, sub)
		} else if len(spec.subs) > 0 {
			for _, s := range spec.subs {
				fmt.Fprintf(&b, "complete -c lambe -n '__fish_seen_subcommand_from %s; and not __fish_seen_subcommand_from %s' -a %s\n", name, strings.Join(spec.subs, " "), s)
			}
		}
		for _, f := range spec.flags {
			line := fmt.Sprintf("complete -c lambe -n %s -l %s -d %s", fishQuote(cond), strings.TrimPrefix(f.name, "--"), fishQuote(f.desc))
			switch {
			case f.file:
				line += " -r -F"
			case len(f.values) > 0:
				line += " -x -a " + fishQuote(strings.Join(f.values, " "))
			case f.takesValue:
				line += " -x"
			}
			b.WriteString(line + "\n")
		}
	}
	return b.String()
}

func fishQuote(s string) string {
	return "'" + strings.NewReplacer(`\`, `\\`, `'`, `\'`).Replace(s) + "'"
}

// runCompletion implements `lambe completion SHELL`.
func runCompletion(args []string, out io.Writer) error {
	fs := flag.NewFlagSet("lambe completion", flag.ContinueOnError)
	if err := parseFlags(fs, args); err != nil {
		return err
	}
	if fs.NArg() != 1 {
		return usageError{errors.New("usage: lambe completion bash|zsh|fish")}
	}
	script, err := completionScript(fs.Arg(0))
	if err != nil {
		return err
	}
	_, err = io.WriteString(out, script)
	return err
}
