// Command gen turns captured `rex api describe METHOD --json` fixtures into
// the Lua table the test stub validates its arguments against, so the stub's
// idea of each Rex method comes from Rex itself and not from memory.
//
// Fixtures live in contrib/rex/testdata/api/revN/METHOD.json, one directory
// per Rex API revision. Capture them read-only:
//
//	rex api describe METHOD --json                 # this machine
//	rex -S macmini api describe METHOD --json      # another host
//
// keeping only name, input_schema and output_schema. Regenerate the table:
//
//	go run ./contrib/rex/internal/gen
package main

import (
	"bytes"
	"cmp"
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"path/filepath"
	"slices"
	"strconv"
	"strings"
)

// fixture is the part of a describe document the stub needs.
type fixture struct {
	Name        string `json:"name"`
	InputSchema struct {
		Properties           map[string]property `json:"properties"`
		Required             []string            `json:"required"`
		AdditionalProperties *bool               `json:"additionalProperties"`
	} `json:"input_schema"`
}

// property is one request field; JSON Schema allows type to be a string or a
// list of strings.
type property struct {
	Type any      `json:"type"`
	Enum []string `json:"enum"`
}

// types returns the property's JSON Schema types, sorted.
func (p property) types() []string {
	var out []string
	switch t := p.Type.(type) {
	case string:
		out = []string{t}
	case []any:
		for _, v := range t {
			if s, ok := v.(string); ok {
				out = append(out, s)
			}
		}
	}
	slices.Sort(out)
	return out
}

func quote(s string) string { return strconv.Quote(s) }

// Generate renders every revN directory under dir as one Lua module.
func Generate(dir string) ([]byte, error) {
	revDirs, err := filepath.Glob(filepath.Join(dir, "rev*"))
	if err != nil {
		return nil, err
	}
	type rev struct {
		n    int
		path string
	}
	var revs []rev
	for _, p := range revDirs {
		n, err := strconv.Atoi(strings.TrimPrefix(filepath.Base(p), "rev"))
		if err != nil {
			return nil, fmt.Errorf("fixture directory %s is not revN", p)
		}
		revs = append(revs, rev{n, p})
	}
	if len(revs) == 0 {
		return nil, fmt.Errorf("no rev* fixture directories in %s", dir)
	}
	slices.SortFunc(revs, func(a, b rev) int { return cmp.Compare(a.n, b.n) })

	var b bytes.Buffer
	b.WriteString("-- Code generated by contrib/rex/internal/gen from contrib/rex/testdata/api; DO NOT EDIT.\n")
	b.WriteString("-- Per Rex API revision, per method: the request fields the server accepts.\n")
	b.WriteString("-- `fields` maps a name to its JSON Schema types (and enum when closed to a set).\n")
	b.WriteString("return {\n")
	for _, r := range revs {
		files, err := filepath.Glob(filepath.Join(r.path, "*.json"))
		if err != nil {
			return nil, err
		}
		slices.Sort(files)
		fmt.Fprintf(&b, "  [%d] = {\n", r.n)
		for _, f := range files {
			data, err := os.ReadFile(f) // #nosec G304 -- fixture path from a directory glob
			if err != nil {
				return nil, err
			}
			var fx fixture
			if err := json.Unmarshal(data, &fx); err != nil {
				return nil, fmt.Errorf("%s: %w", f, err)
			}
			if fx.Name == "" || fx.Name+".json" != filepath.Base(f) {
				return nil, fmt.Errorf("%s: name %q does not match the file", f, fx.Name)
			}
			closed := fx.InputSchema.AdditionalProperties != nil && !*fx.InputSchema.AdditionalProperties
			fmt.Fprintf(&b, "    [%s] = { closed = %t,\n", quote(fx.Name), closed)
			required := slices.Clone(fx.InputSchema.Required)
			slices.Sort(required)
			b.WriteString("      required = {")
			for i, name := range required {
				if i > 0 {
					b.WriteString(", ")
				}
				b.WriteString(quote(name))
			}
			b.WriteString("},\n      fields = {\n")
			names := make([]string, 0, len(fx.InputSchema.Properties))
			for name := range fx.InputSchema.Properties {
				names = append(names, name)
			}
			slices.Sort(names)
			for _, name := range names {
				p := fx.InputSchema.Properties[name]
				var ts []string
				for _, t := range p.types() {
					ts = append(ts, quote(t))
				}
				fmt.Fprintf(&b, "        [%s] = { types = {%s}", quote(name), strings.Join(ts, ", "))
				if len(p.Enum) > 0 {
					var es []string
					for _, e := range p.Enum {
						es = append(es, quote(e))
					}
					fmt.Fprintf(&b, ", enum = {%s}", strings.Join(es, ", "))
				}
				b.WriteString(" },\n")
			}
			b.WriteString("      },\n    },\n")
		}
		b.WriteString("  },\n")
	}
	b.WriteString("}\n")
	return b.Bytes(), nil
}

func main() {
	in := flag.String("in", "contrib/rex/testdata/api", "fixture directory")
	out := flag.String("out", "contrib/rex/test/apischema.lua", "generated Lua file")
	flag.Parse()
	data, err := Generate(*in)
	if err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
	if err := os.WriteFile(*out, data, 0o644); err != nil { // #nosec G306 -- source file, not a secret
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}
